def _seed_neg_sources(cur):
    for s in config.NEG_DEFAULT_SOURCES:
        cur.execute(
            "INSERT INTO neg_sources (kind, name, handle, kz, region) VALUES (%s,%s,%s,%s,%s) "
            "ON CONFLICT (kind, handle) DO NOTHING",
            (s["kind"], s["name"], s["handle"], s.get("kz", True), s.get("region")))


# (версия, SQL или функция(cursor))
MIGRATIONS = [
    (1, SCHEMA_V1),
    (2, SCHEMA_V2),
    (3, _seed_neg_sources),
]
SCHEMA_VERSION = MIGRATIONS[-1][0]
_LOCK_KEY = 7_412_093_551       # произвольное число для pg_advisory_xact_lock


def _current_version(cur) -> int:
    cur.execute("SELECT to_regclass('aml_meta') IS NOT NULL")
    if not cur.fetchone()[0]:
        return 0
    cur.execute("SELECT value FROM aml_meta WHERE key = 'schema_version'")
    row = cur.fetchone()
    return int(row[0]) if row else 0


def ensure_schema(conn) -> int:
    """Доводит схему до актуальной версии. Возвращает номер версии."""
    with conn.cursor() as cur:
        if _current_version(cur) >= SCHEMA_VERSION:
            conn.commit()
            return SCHEMA_VERSION
    with conn.transaction():
        with conn.cursor() as cur:
            cur.execute("SELECT pg_advisory_xact_lock(%s)", (_LOCK_KEY,))
            cur.execute("CREATE TABLE IF NOT EXISTS aml_meta (key text PRIMARY KEY, value text)")
            version = _current_version(cur)
            for v, step in MIGRATIONS:
                if v <= version:
                    continue
                if callable(step):
                    step(cur)
                else:
                    cur.execute(step)
                version = v
            cur.execute("INSERT INTO aml_meta (key, value) VALUES ('schema_version', %s) "
                        "ON CONFLICT (key) DO UPDATE SET value = excluded.value", (str(version),))
    return version


def insert_article(conn, **a) -> bool:
    """True, если статья новая."""
    a.setdefault("collected_at", now())
    cols = ", ".join(a)
    q = ", ".join("%s" for _ in a)
    cur = conn.execute(f"INSERT INTO articles ({cols}) VALUES ({q}) ON CONFLICT (url) DO NOTHING",
                       tuple(a.values()))
    return cur.rowcount > 0


def count(conn, sql: str, params=()) -> int:
    return conn.execute(sql, params).fetchone()[0] or 0
