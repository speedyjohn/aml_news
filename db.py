"""
База PostgreSQL: подключение и схема. С ней работают и main.py, и панель.

Таблицы скрининга (entities, articles, matches) и негативных новостей
(neg_sources, neg_news) создаёт этот модуль; таблицы самой панели
(пользователи, запуски, автозапуск) — Django (manage.py migrate).

Схема версионируется: номер версии хранится в aml_meta, при подключении
недостающие шаги применяются по порядку (под advisory-блокировкой, чтобы
панель и main.py не делали этого одновременно).
"""
from datetime import datetime, timezone

import psycopg

import config


class DatabaseNotConfigured(RuntimeError):
    pass


# ---------------------------------------------------------------------------
# Строки результата: доступ и по имени колонки (r["id"]), и по номеру (r[0])
# ---------------------------------------------------------------------------
class Row(tuple):
    def __new__(cls, values, index):
        obj = super().__new__(cls, values)
        obj._index = index
        return obj

    def __getitem__(self, key):
        if isinstance(key, str):
            return tuple.__getitem__(self, self._index[key])
        return tuple.__getitem__(self, key)

    def keys(self):
        return list(self._index)

    def get(self, key, default=None):
        i = self._index.get(key)
        return default if i is None else tuple.__getitem__(self, i)


def _row_factory(cursor):
    desc = cursor.description
    if desc is None:
        return tuple
    index = {c.name: i for i, c in enumerate(desc)}
    return lambda values: Row(values, index)


def now() -> datetime:
    return datetime.now(timezone.utc)


def dsn(override: str | None = None) -> str:
    url = override or config.DATABASE_URL
    if not url:
        raise DatabaseNotConfigured(
            "Не задан адрес базы PostgreSQL. Запустите setup_postgres.py "
            "(или start.bat) либо пропишите AML_DATABASE_URL в файле .env")
    return url


def connect(url: str | None = None, ensure: bool = True) -> psycopg.Connection:
    conn = psycopg.connect(dsn(url), row_factory=_row_factory, connect_timeout=10,
                           application_name="aml_news", options="-c timezone=UTC")
    if ensure:
        ensure_schema(conn)
    return conn


